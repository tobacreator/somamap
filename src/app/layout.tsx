import type { Metadata } from "next";
import { Geist, Geist_Mono, Newsreader } from "next/font/google";
import "./globals.css";

/**
 * The interface face: Geist, loaded and now actually used.
 *
 * Phase A of the approved design direction (BUILD-REPORT.md Entry 37). Before this phase the
 * scaffold's `body { font-family: Arial, ... }` overrode these variables, so the app rendered in
 * Arial; that rule is gone and the family comes from the --font-sans token, applied here.
 */
const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

/**
 * The expressive face: a humanist serif, used only where the product's subject is language
 * itself - the interview question and the user's own sentence on the card. It is not a decorative
 * flourish: it is the typographic argument that this product is about words.
 */
const newsreader = Newsreader({
  variable: "--font-newsreader",
  subsets: ["latin"],
  display: "swap",
});

/**
 * Product metadata.
 *
 * The scaffold's "Create Next App" / "Generated by create next app" values are gone. The title is
 * the validated title tag from the blueprint's landing-page prompt (Section 9.5), and the
 * description is the approved H1 and subhead from the market validation report's landing table
 * (Chapter 8, Table 9). Both are product positioning, not medical claims: the app describes what
 * it is - a vocabulary and journaling tool - and never what a sensation means.
 */
export const metadata: Metadata = {
  title: "SomaMap - find the words for what you feel in your body",
  description:
    "Point at your body. Find the words. Notice, name, and remember sensations, then bring the words to your appointment.",
  applicationName: "SomaMap",
};

export default function RootLayout({ children }: LayoutProps<"/">) {
  return (
    <html
      lang="en"
      className={`${geistSans.variable} ${geistMono.variable} ${newsreader.variable} font-sans h-full antialiased`}
    >
      <body className="min-h-full flex flex-col">{children}</body>
    </html>
  );
}

