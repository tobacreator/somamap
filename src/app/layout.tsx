import type { Metadata } from "next";
import { Geist, Geist_Mono, Newsreader } from "next/font/google";
import "./globals.css";

import RecoveryRedirect from "@/components/RecoveryRedirect";
import { HOME_H1, HOME_SUBHEAD, HOME_TITLE_TAG } from "@/lib/copy";


/**
 * The interface face: Geist, loaded and now actually used.
 *
 * Phase A of the approved design direction (BUILD-REPORT.md Entry 37). Before this phase the
 * scaffold's `body { font-family: Arial, ... }` overrode these variables, so the app rendered in
 * Arial; that rule is gone and the family comes from the --font-sans token, applied here.
 */
const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

/**
 * The expressive face: a humanist serif, used only where the product's subject is language
 * itself - the interview question and the user's own sentence on the card. It is not a decorative
 * flourish: it is the typographic argument that this product is about words.
 */
const newsreader = Newsreader({
  variable: "--font-newsreader",
  subsets: ["latin"],
  display: "swap",
});

/**
 * Product metadata.
 *
 * The scaffold's "Create Next App" / "Generated by create next app" values are gone. Both strings now come
 * from `src/lib/copy.ts` instead of being written out here: the title is `HOME_TITLE_TAG`, and the
 * description is the landing page's own H1 and lead line.
 *
 * They used to be duplicated literals, and the description had already drifted: it was still the market
 * validation report's subhead - "bring the words to your appointment" - after the page itself had moved
 * on. That is exactly what a second copy of production copy invites, so the second copy is gone.
 *
 * Both are product positioning, not medical claims: the app describes what it is - a vocabulary and
 * journaling tool - and never what a sensation means.
 */
export const metadata: Metadata = {
  title: HOME_TITLE_TAG,
  description: `${HOME_H1} ${HOME_SUBHEAD}`,
  applicationName: "SomaMap",
};

export default function RootLayout({ children }: LayoutProps<"/">) {
  return (
    <html
      lang="en"
      className={`${geistSans.variable} ${geistMono.variable} ${newsreader.variable} font-sans h-full antialiased`}
    >
      <body className="min-h-full flex flex-col">
        {/*
          One mount for the whole app: a recovery link lands wherever the project's configured address points
          (the root, in this deployment), and the fragment it carries can only be read in the browser. This
          forwards a recovery payload to `/reset-password` and does nothing on any other page view.
        */}
        <RecoveryRedirect />

        {children}
      </body>
    </html>
  );
}

